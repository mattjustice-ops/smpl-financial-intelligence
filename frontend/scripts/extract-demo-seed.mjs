/**
 * Extract TS_DATA + SMPL_DEMO_WF_TABLE + workforce heads/reqs (WF_DEMO) from board/index.html
 * into shared/smpl-demo-seed.js
 * Run: node scripts/extract-demo-seed.mjs
 */
import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const boardHtml = fs.readFileSync(path.join(root, "public/board/index.html"), "utf8");

function extractJsObject(html, varName) {
  const prefixes = [`var ${varName}`, `const ${varName}`, `let ${varName}`];
  let start = -1;
  for (const p of prefixes) {
    start = html.indexOf(p);
    if (start >= 0) break;
  }
  if (start < 0) return null;
  const eq = html.indexOf("=", start);
  const brace = html.indexOf("{", eq);
  if (brace < 0) return null;
  let depth = 0;
  let inStr = false;
  let strCh = "";
  for (let i = brace; i < html.length; i++) {
    const c = html[i];
    const prev = html[i - 1];
    if (inStr) {
      if (c === strCh && prev !== "\\") inStr = false;
      continue;
    }
    if (c === '"' || c === "'") {
      inStr = true;
      strCh = c;
      continue;
    }
    if (c === "{") depth++;
    else if (c === "}") {
      depth--;
      if (depth === 0) return html.slice(brace, i + 1);
    }
  }
  return null;
}

const tsSource = extractJsObject(boardHtml, "TS_DATA");
const wfSource = extractJsObject(boardHtml, "SMPL_DEMO_WF_TABLE");
const workforceSource = extractJsObject(boardHtml, "WF_DEMO");
if (!tsSource || !wfSource || !workforceSource) {
  console.error("Failed to extract demo seed from board/index.html");
  process.exit(1);
}
const workforce = JSON.parse(workforceSource);
const WORKFORCE_SEED_KEYS = ["months", "close_month", "departments", "heads", "heads_total", "heads_source", "reqs"];
const workforceSeed = Object.fromEntries(WORKFORCE_SEED_KEYS.map((k) => [k, workforce[k] ?? null]));

const out = `/** Auto-generated by scripts/extract-demo-seed.mjs — do not edit by hand */
(function (g) {
  "use strict";
  g.SMPL_DEMO_TS_DATA = ${tsSource};
  g.SMPL_DEMO_WF_TABLE = ${wfSource};
  g.SMPL_DEMO_WORKFORCE = ${JSON.stringify(workforceSeed)};
  if (g.SMPLOutlook && g.SMPLOutlook.registerDemoData) {
    g.SMPLOutlook.registerDemoData(g.SMPL_DEMO_TS_DATA, g.SMPL_DEMO_WF_TABLE);
  }
})(typeof window !== "undefined" ? window : globalThis);
`;

const outPath = path.join(root, "public/shared/smpl-demo-seed.js");
fs.writeFileSync(outPath, out, "utf8");
console.log("Wrote", outPath, `(${(out.length / 1024).toFixed(1)} KB)`);
